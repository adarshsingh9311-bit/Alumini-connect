import React, { useState } from "react";
import { ShieldCheck, ShieldAlert, CheckCircle, XCircle, Edit3, Send, AlertTriangle } from "lucide-react";

export default function OutreachApprovalModal({
  isOpen,
  onClose,
  workflowState,
  onApprove,
  onReject
}) {
  if (!isOpen || !workflowState) return null;

  const [message, setMessage] = useState(workflowState.sanitized_outreach || "");
  const [isEditing, setIsEditing] = useState(false);
  const mentor = workflowState.selected_mentor;

  function handleSaveEdit() {
    setIsEditing(false);
  }

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-black/80 backdrop-blur-sm animate-in fade-in duration-200">
      <div className="bg-white rounded-3xl border border-slate-200 max-w-2xl w-full p-6 sm:p-8 text-slate-900 shadow-2xl relative space-y-6">
        
        {/* Modal Header */}
        <div className="flex items-start justify-between border-b border-slate-100 pb-4">
          <div className="space-y-1">
            <div className="inline-flex items-center space-x-1.5 px-3 py-1 rounded-full text-xs font-bold bg-amber-100 text-amber-900">
              <ShieldCheck className="w-4 h-4 text-amber-700" />
              <span>Human-in-the-Loop Approval Gate</span>
            </div>
            <h2 className="text-xl sm:text-2xl font-black text-slate-900">
              Review &amp; Approve Outreach Draft
            </h2>
            <p className="text-xs text-slate-500">
              Generated by <strong>Outreach Synthesis Agent</strong> for{" "}
              <span className="font-semibold text-slate-800">{mentor?.name}</span> ({mentor?.current_company}).
            </p>
          </div>
        </div>

        {/* PII & Privacy Notice */}
        <div className="p-4 rounded-2xl bg-amber-50 border border-amber-200/80 space-y-2 text-xs text-amber-950">
          <div className="flex items-center space-x-2 font-bold">
            <ShieldAlert className="w-4 h-4 text-amber-700" />
            <span>Guardrail Redactions Applied</span>
          </div>
          <p className="leading-relaxed">
            The Trust Layer detected private contact elements in the draft:{" "}
            <strong>{workflowState.pii_flags?.join(", ") || "Email & Phone"}</strong>. These have been masked as{" "}
            <code className="bg-amber-100 px-1 py-0.5 rounded font-mono">[REDACTED]</code> prior to transmission.
          </p>
        </div>

        {/* Draft Editor / Viewer */}
        <div className="space-y-2">
          <div className="flex items-center justify-between text-xs font-bold text-slate-700">
            <span>Message Content (Editable)</span>
            {!isEditing ? (
              <button
                type="button"
                onClick={() => setIsEditing(true)}
                className="text-[#592106] hover:underline flex items-center gap-1"
              >
                <Edit3 className="w-3.5 h-3.5" />
                <span>Edit Draft</span>
              </button>
            ) : (
              <button
                type="button"
                onClick={handleSaveEdit}
                className="text-emerald-700 font-bold hover:underline"
              >
                Save Changes
              </button>
            )}
          </div>

          {isEditing ? (
            <textarea
              rows={8}
              value={message}
              onChange={(e) => setMessage(e.target.value)}
              className="w-full p-4 rounded-2xl border border-slate-300 font-sans text-xs text-slate-900 focus:outline-none focus:ring-2 focus:ring-[#ffcc4e] leading-relaxed"
            />
          ) : (
            <div className="p-4 rounded-2xl bg-slate-50 border border-slate-200 text-xs text-slate-800 font-mono whitespace-pre-wrap leading-relaxed max-h-60 overflow-y-auto">
              {message}
            </div>
          )}
        </div>

        {/* Mentor Capacity Summary */}
        <div className="p-3.5 rounded-xl bg-slate-100 border border-slate-200 flex items-center justify-between text-xs text-slate-600">
          <div>
            <span>Recipient: </span>
            <strong className="text-slate-900">{mentor?.name}</strong> ({mentor?.current_designation})
          </div>
          <div>
            <span>Active Capacity: </span>
            <span className="font-bold text-emerald-700">
              {mentor?.current_load}/{mentor?.capacity} Mentees (Available)
            </span>
          </div>
        </div>

        {/* Action Controls */}
        <div className="flex flex-col sm:flex-row items-center justify-end gap-3 pt-2 border-t border-slate-100">
          <button
            type="button"
            onClick={() => onReject(workflowState.workflow_id)}
            className="w-full sm:w-auto px-5 py-2.5 rounded-xl border border-rose-200 bg-rose-50 text-rose-700 hover:bg-rose-100 font-bold text-xs flex items-center justify-center gap-2 transition"
          >
            <XCircle className="w-4 h-4" />
            <span>Reject Draft (Stop Pipeline)</span>
          </button>

          <button
            type="button"
            onClick={() => onApprove(workflowState.workflow_id, message)}
            className="w-full sm:w-auto px-6 py-2.5 rounded-xl bg-[#592106] hover:bg-[#472510] text-[#ffcc4e] font-extrabold text-xs flex items-center justify-center gap-2 shadow-lg transition"
          >
            <Send className="w-4 h-4" />
            <span>Approve &amp; Send (Simulated)</span>
          </button>
        </div>

      </div>
    </div>
  );
}
