/**
 * Deterministically select a thought for a given calendar date (YYYY-MM-DD).
 * 
 * Mathematical properties:
 * 1. Consistent throughout the day: Every user sees the exact same thought on the same date.
 * 2. Deterministic: Page reloads/refreshes never randomly change the thought.
 * 3. Automatic rotation: Progresses to the next thought at midnight without any admin action.
 * 4. Exhausts collection before repeating: Sequences through the entire collection sequentially.
 * 5. Handles empty collection gracefully: Returns null if no thoughts exist.
 */
export function getThoughtForDate(targetDateStr) {
  if (!APPROVED_DAILY_THOUGHTS || APPROVED_DAILY_THOUGHTS.length === 0) {
    return null;
  }

  // Target date format YYYY-MM-DD
  const dateStr = targetDateStr || new Date().toISOString().split("T")[0];
  const parts = dateStr.split("-").map(Number);
  if (parts.length !== 3 || isNaN(parts[0]) || isNaN(parts[1]) || isNaN(parts[2])) {
    return APPROVED_DAILY_THOUGHTS[0];
  }

  const [year, month, day] = parts;

  // Fixed institutional epoch: 2026-01-01
  const epoch = new Date(Date.UTC(2026, 0, 1)).getTime();
  const current = new Date(Date.UTC(year, month - 1, day)).getTime();
  const dayDifference = Math.floor((current - epoch) / (1000 * 60 * 60 * 24));

  const total = APPROVED_DAILY_THOUGHTS.length;
  // Positive modulo
  const index = ((dayDifference % total) + total) % total;

  return APPROVED_DAILY_THOUGHTS[index];
}
